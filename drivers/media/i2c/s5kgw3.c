/*
 * Samsung S5KGW3 (50 Mpixel, 4-cell, 4-lane MIPI CSI-2) sensor driver for the
 * rear main camera of the Galaxy M52 5G (SM-M526B).
 *
 * The register sequences are the Samsung LSI setfiles found in the MediaTek
 * imgsensor driver of the Galaxy A32 kernel sources (4624x3468 binned mode,
 * 30 fps).  Table words are sent verbatim, high byte first.  The setfiles
 * assume a 26 MHz EXTCLK; this board supplies 19.2 MHz, so EXTCLK (0x0136)
 * and the two PLL pre-dividers (0x0304, 0x030e) are patched (4 -> 3), which
 * keeps the MIPI rate within 1.5 % of the original (2022.4 Mbit/s per lane).
 * 16-bit exposure/gain/frame-length registers are big-endian (high byte first).
 *
 * m52xq: third mode, the full 9248x6936 frame (MTK "custom2", 64 Mpixel). The sensor outputs
 * a hardware re-mosaiced Bayer frame there (SENSOR_OUTPUT_FORMAT_RAW_4CELL_HW_BAYER); the
 * A32 driver writes no calibration for it (WRITE_SENSOR_CAL_FOR_GGC 0). Same PLL and MIPI
 * rate as the 4624x3468 mode, line 11184, frame 7116 lines (~10 fps).
 */
