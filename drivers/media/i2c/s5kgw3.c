static int s5kgw3_power_on(struct device *dev)
{
	struct s5kgw3 *gw = to_s5kgw3(dev_get_drvdata(dev));
	int i, ret;

	gpiod_set_value_cansleep(gw->reset_gpio, 1);

	/*
	 * Sequence traced on the stock Lineage 23 camera HAL (ftrace of
	 * CAM-SENSOR power up): vio, vdig, vaf, vana, then reset is released
	 * BEFORE the master clock starts, about 11 ms later the clock is
	 * enabled and about 15 ms after that the first I2C access follows.
	 */
	for (i = 0; i < S5KGW3_NUM_SUPPLIES; i++) {
		ret = regulator_enable(gw->supplies[i].consumer);
		if (ret) {
			dev_err(dev, "failed to enable %s\n", gw->supplies[i].supply);
			goto err_supplies;
		}
		usleep_range(5000, 6000);
	}

	gpiod_set_value_cansleep(gw->reset_gpio, 0);
	usleep_range(11000, 12000);

	ret = clk_prepare_enable(gw->xclk);
	if (ret) {
		dev_err(dev, "failed to enable the clock\n");
		gpiod_set_value_cansleep(gw->reset_gpio, 1);
		goto err_supplies;
	}

	msleep(15);
	return 0;

err_supplies:
	while (--i >= 0)
		regulator_disable(gw->supplies[i].consumer);
	return ret;
}

static int s5kgw3_power_off(struct device *dev)
{
	struct s5kgw3 *gw = to_s5kgw3(dev_get_drvdata(dev));
	int i;

	gw->initialized = false;
	/* stock order: clock, reset, then the supplies in reverse */
	clk_disable_unprepare(gw->xclk);
	gpiod_set_value_cansleep(gw->reset_gpio, 1);
	for (i = S5KGW3_NUM_SUPPLIES - 1; i >= 0; i--)
		regulator_disable(gw->supplies[i].consumer);
	return 0;
}

static int s5kgw3_check_hwcfg(struct device *dev)
{
	struct v4l2_fwnode_endpoint ep = { .bus_type = V4L2_MBUS_CSI2_DPHY };
	struct fwnode_handle *endpoint;
	int ret;

	endpoint = fwnode_graph_get_next_endpoint(dev_fwnode(dev), NULL);
	if (!endpoint)
		return dev_err_probe(dev, -EINVAL, "endpoint node not found\n");

	ret = v4l2_fwnode_endpoint_alloc_parse(endpoint, &ep);
	fwnode_handle_put(endpoint);
	if (ret)
		return ret;

	if (ep.bus.mipi_csi2.num_data_lanes != S5KGW3_LANES) {
		dev_err(dev, "only %d data lanes are supported\n", S5KGW3_LANES);
		ret = -EINVAL;
	} else if (ep.nr_of_link_frequencies != 1 ||
		   ep.link_frequencies[0] != S5KGW3_LINK_FREQ) {
		dev_err(dev, "link-frequencies must be %lld\n", S5KGW3_LINK_FREQ);
		ret = -EINVAL;
	}

	v4l2_fwnode_endpoint_free(&ep);
	return ret;
}

static int s5kgw3_probe(struct i2c_client *client)
{
	struct device *dev = &client->dev;
	struct s5kgw3 *gw;
	u64 id;
	int ret, i;

	gw = devm_kzalloc(dev, sizeof(*gw), GFP_KERNEL);
	if (!gw)
		return -ENOMEM;
	gw->dev = dev;
	gw->mode = &s5kgw3_modes[0];

	ret = s5kgw3_check_hwcfg(dev);
	if (ret)
		return ret;

	gw->regmap = devm_cci_regmap_init_i2c(client, 16);
	if (IS_ERR(gw->regmap))
		return dev_err_probe(dev, PTR_ERR(gw->regmap), "cci regmap\n");

	gw->xclk = devm_v4l2_sensor_clk_get(dev, NULL);
	if (IS_ERR(gw->xclk))
		return dev_err_probe(dev, PTR_ERR(gw->xclk), "failed to get the clock\n");
	if (clk_get_rate(gw->xclk) != S5KGW3_XCLK_FREQ)
		return dev_err_probe(dev, -EINVAL, "unsupported clock rate %lu\n",
				     clk_get_rate(gw->xclk));

	for (i = 0; i < S5KGW3_NUM_SUPPLIES; i++)
		gw->supplies[i].supply = s5kgw3_supply_names[i];
	ret = devm_regulator_bulk_get(dev, S5KGW3_NUM_SUPPLIES, gw->supplies);
	if (ret)
		return dev_err_probe(dev, ret, "failed to get the supplies\n");

	gw->reset_gpio = devm_gpiod_get_optional(dev, "reset", GPIOD_OUT_HIGH);
	if (IS_ERR(gw->reset_gpio))
		return dev_err_probe(dev, PTR_ERR(gw->reset_gpio), "reset gpio\n");

	v4l2_i2c_subdev_init(&gw->sd, client, &s5kgw3_subdev_ops);
	gw->sd.internal_ops = &s5kgw3_internal_ops;

	ret = s5kgw3_power_on(dev);
	if (ret)
		return ret;

	ret = cci_read(gw->regmap, S5KGW3_REG_CHIP_ID, &id, NULL);
	if (ret) {
		dev_err(dev, "failed to read the chip id (%d)\n", ret);
		goto err_power_off;
	}
	if (id != S5KGW3_CHIP_ID) {
		dev_err(dev, "unexpected chip id 0x%04llx\n", id);
		ret = -ENODEV;
		goto err_power_off;
	}
	dev_info(dev, "detected S5KGW3 (0x%04llx)\n", id);

	ret = s5kgw3_init_controls(gw);
	if (ret)
		goto err_power_off;

	gw->sd.flags |= V4L2_SUBDEV_FL_HAS_DEVNODE;
	gw->sd.entity.function = MEDIA_ENT_F_CAM_SENSOR;
	gw->pad.flags = MEDIA_PAD_FL_SOURCE;
	ret = media_entity_pads_init(&gw->sd.entity, 1, &gw->pad);
	if (ret)
		goto err_ctrls;

	gw->sd.state_lock = gw->ctrls.lock;
	ret = v4l2_subdev_init_finalize(&gw->sd);
	if (ret)
		goto err_entity;

	pm_runtime_set_active(dev);
	pm_runtime_get_noresume(dev);
	pm_runtime_enable(dev);
	pm_runtime_set_autosuspend_delay(dev, 1000);
	pm_runtime_use_autosuspend(dev);
	pm_runtime_put_autosuspend(dev);

	ret = v4l2_async_register_subdev_sensor(&gw->sd);
	if (ret) {
		dev_err(dev, "failed to register the subdev (%d)\n", ret);
		goto err_cleanup;
	}
	return 0;

err_cleanup:
	v4l2_subdev_cleanup(&gw->sd);
	pm_runtime_disable(dev);
	pm_runtime_set_suspended(dev);
err_entity:
	media_entity_cleanup(&gw->sd.entity);
err_ctrls:
	v4l2_ctrl_handler_free(&gw->ctrls);
err_power_off:
	s5kgw3_power_off(dev);
	return ret;
}

static void s5kgw3_remove(struct i2c_client *client)
{
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct s5kgw3 *gw = to_s5kgw3(sd);

	v4l2_async_unregister_subdev(sd);
	v4l2_subdev_cleanup(sd);
	media_entity_cleanup(&sd->entity);
	v4l2_ctrl_handler_free(&gw->ctrls);

	pm_runtime_disable(&client->dev);
	if (!pm_runtime_status_suspended(&client->dev))
		s5kgw3_power_off(&client->dev);
	pm_runtime_set_suspended(&client->dev);
}

